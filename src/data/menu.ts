/** Sort order is derived per category so admin drag-reorder has stable integers. */
export const MENU_ITEMS: MenuItem[] = (() => {
  const counters = new Map<string, number>()
  return raw.map(({ groups, ...item }) => {
    const next = (counters.get(item.categoryId) ?? 0) + 1
    counters.set(item.categoryId, next)
    return { ...item, optionGroups: groups, sortOrder: next }
  })
})()
